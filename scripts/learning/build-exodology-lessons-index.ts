/** Regenerate data/exodology-new-lessons/index.ts from the lesson files. */
import { readdirSync, writeFileSync } from 'fs'
const DIR = 'data/exodology-new-lessons'
const files = readdirSync(DIR).filter((f) => /^[asf]-m\d+-n\d+\.ts$/.test(f)).sort()
const ident = (f: string) => 'l_' + f.replace(/\.ts$/, '').replace(/-/g, '_')
writeFileSync(`${DIR}/index.ts`, `// Generated by scripts/learning/build-exodology-lessons-index.ts. Do not edit.
import type { NewExodologyLesson } from './types'
${files.map((f) => `import ${ident(f)} from './${f.replace(/\.ts$/, '')}'`).join('\n')}

export const NEW_EXODOLOGY_LESSONS: Record<string, NewExodologyLesson> = {
${files.map((f) => `  '${f.replace(/\.ts$/, '')}': ${ident(f)},`).join('\n')}
}
`)
console.log(`indexed ${files.length} new Exodology lessons`)
