/** Regenerate data/exodology-expanded-lessons/index.ts from the lesson files. */
import { readdirSync, writeFileSync } from 'fs'
const DIR = 'data/exodology-expanded-lessons'
const files = readdirSync(DIR).filter((f) => /^[asf]-m\d+-l\d+\.ts$/.test(f)).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
const ident = (f: string) => 'l_' + f.replace(/\.ts$/, '').replace(/-/g, '_')
writeFileSync(`${DIR}/index.ts`, `// Generated by scripts/learning/build-exodology-expanded-index.ts. Do not edit.
import type { ExpandedExodologyLesson } from './types'
${files.map((f) => `import ${ident(f)} from './${f.replace(/\.ts$/, '')}'`).join('\n')}

export const EXPANDED_EXODOLOGY_LESSONS: Record<string, ExpandedExodologyLesson> = {
${files.map((f) => `  '${f.replace(/\.ts$/, '')}': ${ident(f)},`).join('\n')}
}
`)
console.log(`indexed ${files.length} expanded Exodology lessons`)
