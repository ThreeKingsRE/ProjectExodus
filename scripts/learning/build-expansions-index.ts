/**
 * Regenerate data/modules/expanded/index.ts from the expansion files.
 *   npx tsx scripts/learning/build-expansions-index.ts          # write
 *   npx tsx scripts/learning/build-expansions-index.ts --check  # fail if stale
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'fs'
import { join } from 'path'

const ROOT = 'data/modules/expanded'
const OUT = join(ROOT, 'index.ts')
const files: string[] = []
for (const topic of readdirSync(ROOT).sort()) {
  const dir = join(ROOT, topic)
  if (!statSync(dir).isDirectory()) continue
  for (const f of readdirSync(dir).sort()) if (f.endsWith('.ts')) files.push(`${topic}/${f.replace(/\.ts$/, '')}`)
}
const ident = (p: string) => 'x_' + p.replace(/[^a-zA-Z0-9]/g, '_')
const src = `// Generated by scripts/learning/build-expansions-index.ts. Do not edit.
import type { ModuleExpansion } from './types'
${files.map((f) => `import ${ident(f)} from './${f}'`).join('\n')}

export const MODULE_EXPANSIONS: ModuleExpansion[] = [
${files.map((f) => `  ${ident(f)},`).join('\n')}
]
`
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== src) { console.error(`${OUT} is out of date: run npx tsx scripts/learning/build-expansions-index.ts`); process.exit(1) }
  console.log(`${OUT} up to date (${files.length} expansions)`)
} else {
  writeFileSync(OUT, src)
  console.log(`Wrote ${OUT} with ${files.length} expansions`)
}
